#!/usr/bin/env python3
"""Generate data for the sprite-subtitle prototype ROM (proto.s).

Produces in OUTDIR:
  data.bin   24 KiB blob mapped at CPU $8000-$DFFF (ROM banks 1-3): palettes,
             BG tiles + BAT for a fake "picture" with a black lower band, and
             per-cue sprite pattern data + full 64-entry SAT images.
  data.inc   ca65 constants: init block table and the cue table.
Cue text defaults to real lines from script/xak3_cutscenes.tsv.
"""
import argparse, csv, os, struct, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from font_build import Font, to_sprites

BASE = 0x8000
VRAM_BAT, VRAM_TILES, VRAM_BUF = 0x0000, 0x1000, (0x4000, 0x5000)
VRAM_SAT = 0x7F00
LINE_Y = (184, 204)       # repo's native subtitle band rows (SAT Y 248 / 268)
SPR_ATTR = 0x0080         # 16x16, palette 0, in front of BG
BAND_TOP_ROW = 23         # BAT rows >= 23 (Y >= 184) stay black

def rgb9(r, g, b):  # 0-7 each -> GGGRRRBBB
    return (g << 6) | (r << 3) | b

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir")
    ap.add_argument("--cues", default="VS1-001,VS1-004,VS1-007")
    ap.add_argument("--frames", default="30,150,270")
    ap.add_argument("--tsv", default=os.path.join(os.path.dirname(os.path.dirname(HERE)), "script/xak3_cutscenes.tsv"))
    a = ap.parse_args()
    font = Font()
    rows = {r["cue_id"]: r for r in csv.DictReader(open(a.tsv, encoding="utf-8"), delimiter="\t", quoting=csv.QUOTE_NONE)}
    blob = bytearray()
    def put(b, align=2):
        while len(blob) % align: blob.append(0)
        off = len(blob); blob.extend(b); return BASE + off
    # palettes: 512 colors. BG palettes 0-15: color0 black, color1/2 sky shades per row band.
    pal = [0] * 512
    for p in range(16):
        shade = min(7, 1 + p // 2)
        pal[p * 16 + 1] = rgb9(shade // 3, shade // 2, shade)
        pal[p * 16 + 2] = rgb9(shade // 2, shade // 2 + 1, min(7, shade + 1))
    pal[256 + 1] = rgb9(7, 7, 7)   # sprite pal 0: text white
    pal[256 + 2] = rgb9(1, 1, 1)   # shadow
    init = [("VCE", 0, put(struct.pack("<512H", *pal)), 1024)]
    # tiles: index 0x100 blank, 0x101 dither 1/2
    t_blank = struct.pack("<16H", *([0] * 16))
    t_dith = struct.pack("<16H", *([(0x55 << 8) | 0xAA, (0xAA << 8) | 0x55] * 4 + [0] * 8))
    init.append(("VRAM", VRAM_TILES, put(t_blank + t_dith), 64))
    bat = []
    for row in range(32):
        for col in range(32):
            if row < BAND_TOP_ROW and 4 <= col < 28 and 2 <= row:
                bat.append(((row * 15 // BAND_TOP_ROW) << 12) | 0x101)
            else:
                bat.append(0x100)
    init.append(("VRAM", VRAM_BAT, put(struct.pack("<1024H", *bat)), 2048))
    cues = []
    frames = [int(x) for x in a.frames.split(",")]
    ids = a.cues.split(",")
    for i, (cid, fr) in enumerate(zip(ids, frames)):
        if cid == "STRESS":   # worst case allowed by lint: 2 lines x 240 px = 2 x 15 sprites
            text = "M" * 40 + "|" + "W" * 40
        else:
            text = rows[cid]["en_subtitle"]
        lines = text.split("|")
        buf = VRAM_BUF[i % 2]
        pats, sat = bytearray(), []
        ys = LINE_Y if len(lines) == 2 else LINE_Y[1:]
        for ln, y in zip(lines, ys):
            spr, x = to_sprites(font.render(ln))
            for k, s in enumerate(spr):
                addr = buf + len(pats) // 2
                pats += s
                sat.append((y + 64, x + 16 * k + 32, addr >> 5, SPR_ATTR))
        assert len(sat) <= 64 and len(pats) <= 0x2000
        sat_img = b"".join(struct.pack("<4H", *e) for e in sat) + b"\0" * (8 * (64 - len(sat)))
        cues.append((fr, put(pats), len(pats), buf, put(sat_img), cid, text, len(sat)))
    cues.append((0xFFFF, 0, 0, 0, 0, "end", "", 0))
    assert len(blob) <= 0x6000, hex(len(blob))
    blob.extend(b"\0" * (0x6000 - len(blob)))
    os.makedirs(a.outdir, exist_ok=True)
    open(os.path.join(a.outdir, "data.bin"), "wb").write(blob)
    with open(os.path.join(a.outdir, "data.inc"), "w") as o:
        o.write("; generated by gen_proto.py\n")
        o.write(f"VRAM_SAT = ${VRAM_SAT:04X}\nNUM_INIT = {len(init)}\n")
        o.write("init_tab: ; kind(0=VRAM,1=VCE), dst, src, len\n")
        for kind, dst, src, ln in init:
            o.write(f"  .word {1 if kind == 'VCE' else 0}, ${dst:04X}, ${src:04X}, ${ln:04X}\n")
        o.write("cue_tab: ; frame, pat_src, pat_len, vram_dst, sat_src\n")
        for fr, src, ln, buf, sat, cid, text, n in cues:
            o.write(f"  .word ${fr:04X}, ${src:04X}, ${ln:04X}, ${buf:04X}, ${sat:04X} ; {cid} {n} sprites {text!r}\n")
    for c in cues[:-1]:
        print(f"cue {c[5]} @frame {c[0]}: {c[7]} sprites, {c[2]} B patterns -> VRAM ${c[3]:04X}  {c[6]!r}")

if __name__ == "__main__":
    main()
